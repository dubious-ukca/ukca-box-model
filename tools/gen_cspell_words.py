#!/usr/bin/env python3
"""Generate .cspell/code-words.txt: every word used in Fortran code.

The spell checker (cspell.json) only checks comments, but comments often
mention variable and routine names. This script collects the words that make
up every identifier in the code (outside comments and strings) of the box
model and the UKCA submodule, split at underscores, so those names are never
reported as typos. Whatever cspell still flags in a comment is then a genuine
misspelling or a new word.

Rerun after adding code:

    tools/gen_cspell_words.py
"""

import glob
import re
from pathlib import Path

MIN_LENGTH = 4    # matches minWordLength in cspell.json
OUT = Path(".cspell/code-words.txt")
SOURCES = ["src/**/*.F90", "ukca/src/**/*.F90"]


def code_words(path):
    words = set()
    with open(path, errors="ignore") as f:
        for line in f:
            code = line.split("!")[0]
            code = re.sub(r"'[^']*'|\"[^\"]*\"", " ", code)
            for token in re.findall(r"[A-Za-z][A-Za-z0-9_]*", code):
                for word in token.split("_"):
                    if len(word) >= MIN_LENGTH and word.isalpha():
                        words.add(word.lower())
    return words


def main():
    words = set()
    for pattern in SOURCES:
        for path in glob.glob(pattern, recursive=True):
            words |= code_words(path)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "# Generated by tools/gen_cspell_words.py - do not edit.\n"
        + "\n".join(sorted(words)) + "\n")
    print(f"wrote {len(words)} words to {OUT}")


if __name__ == "__main__":
    main()
